# --- 3.1  Пересечение отрезков ------------------------------------

def on_segment(p: tuple, q: tuple, r: tuple) -> bool:
    """
    Проверяет, лежит ли точка r на отрезке pq
    при условии, что p, q, r коллинеарны (cross = 0).

    Достаточно проверить, что координаты r находятся
    в пределах min/max координат p и q.
    """
    if (min(p[0], q[0]) <= r[0] <= max(p[0], q[0]) and
            min(p[1], q[1]) <= r[1] <= max(p[1], q[1])):
        return True
    return False


def segments_intersect(a: tuple, b: tuple, c: tuple, d: tuple) -> bool:
    """
    Проверяет, пересекаются ли отрезки AB и CD.

    Основная идея:
    1. Вычисляем 4 ориентации:
       d1 = cross(C, D, A)  — положение A относительно прямой CD
       d2 = cross(C, D, B)  — положение B относительно прямой CD
       d3 = cross(A, B, C)  — положение C относительно прямой AB
       d4 = cross(A, B, D)  — положение D относительно прямой AB

    2. «Правильное» пересечение (X-образное):
       d1 и d2 разных знаков  И  d3 и d4 разных знаков
       → точки A,B по разные стороны от CD, и C,D — от AB

    3. Граничные случаи (коллинеарность, касание):
       Если какой-то cross = 0 → точка лежит на прямой,
       проверяем, попадает ли она в отрезок через on_segment.

    Сложность: O(1) — фиксированное число арифметических операций.
    """
    d1 = cross(c, d, a)
    d2 = cross(c, d, b)
    d3 = cross(a, b, c)
    d4 = cross(a, b, d)

    # Случай 1: правильное пересечение
    # d1 и d2 имеют разные знаки (один > 0, другой < 0)
    # d3 и d4 имеют разные знаки
    if ((d1 > 0 and d2 < 0) or (d1 < 0 and d2 > 0)) and \
            ((d3 > 0 and d4 < 0) or (d3 < 0 and d4 > 0)):
        return True

    # Случай 2: граничные (коллинеарные) случаи
    # Если cross = 0, точка лежит на прямой → проверяем отрезок
    if d1 == 0 and on_segment(c, d, a):
        return True
    if d2 == 0 and on_segment(c, d, b):
        return True
    if d3 == 0 and on_segment(a, b, c):
        return True
    if d4 == 0 and on_segment(a, b, d):
        return True

    return False


# --- 3.2  Пересечение многоугольников -----------------------------

def polygons_intersect(poly1: list[tuple], poly2: list[tuple]) -> bool:
    """
    Проверяет, пересекаются ли два многоугольника.

    Два случая пересечения:
    1. Хотя бы одно ребро poly1 пересекает хотя бы одно ребро poly2
       → границы пересекаются.
    2. Один многоугольник полностью внутри другого
       → рёбра не пересекаются, но одна вершина лежит внутри.

    Для случая 2 достаточно проверить одну вершину каждого
    многоугольника внутри другого (если она внутри, то и весь
    многоугольник внутри, раз рёбра не пересекаются).

    Сложность: O(n * m), где n и m — числа вершин.
    """
    n = len(poly1)
    m = len(poly2)

    # Проверка 1: пересечение рёбер
    for i in range(n):
        a = poly1[i]
        b = poly1[(i + 1) % n]
        for j in range(m):
            c = poly2[j]
            d = poly2[(j + 1) % m]
            if segments_intersect(a, b, c, d):
                return True

    # Проверка 2: один полностью внутри другого
    # Достаточно проверить одну вершину каждого
    if point_in_polygon(poly1[0][0], poly1[0][1], poly2):
        return True
    if point_in_polygon(poly2[0][0], poly2[0][1], poly1):
        return True

    return False


