def dist(a: tuple, b: tuple) -> float:
    """
    Расстояние между двумя точками на плоскости.
    Формула: sqrt((xB - xA)² + (yB - yA)²)
    """
    return math.sqrt((b[0] - a[0]) ** 2 + (b[1] - a[1]) ** 2)


def cross(o: tuple, a: tuple, b: tuple) -> float:
    """
    Псевдоскалярное (векторное) произведение векторов OA и OB.
    Определяет ориентацию тройки точек O, A, B:
      > 0  →  поворот против часовой (CCW)
      < 0  →  поворот по часовой (CW)
      = 0  →  точки коллинеарны

    Формула: (Ax - Ox) * (By - Oy) - (Ay - Oy) * (Bx - Ox)
    """
    return (a[0] - o[0]) * (b[1] - o[1]) - (a[1] - o[1]) * (b[0] - o[0])


# ══════════════════════════════════════════════════════════════════
#  ЗАДАНИЕ 1 — Периметр и площадь многоугольника
# ══════════════════════════════════════════════════════════════════

def perimeter(polygon: list[tuple]) -> float:
    """
    Вычисляет периметр многоугольника — сумму длин всех рёбер,
    включая замыкающее ребро (последняя вершина → первая).

    Сложность: O(n), где n — число вершин.
    """
    n = len(polygon)
    total = 0.0
    for i in range(n):
        # Ребро от вершины i к вершине (i+1) % n
        # Оператор % n замыкает многоугольник: последняя → первая
        total += dist(polygon[i], polygon[(i + 1) % n])
    return total


def area(polygon: list[tuple]) -> float:
    """
    Вычисляет площадь простого многоугольника по формуле Гаусса (Shoelace).

    Формула:  S = 0.5 * |Σ (xi * y(i+1) - x(i+1) * yi)|
    Индексы берутся по модулю n (замыкание).

    Знак суммы зависит от направления обхода вершин:
      CCW (против часовой) → положительная
      CW  (по часовой)     → отрицательная
    Берём abs(), чтобы результат всегда был ≥ 0.

    Сложность: O(n).
    """
    n = len(polygon)
    s = 0.0
    for i in range(n):
        x_i, y_i = polygon[i]
        x_next, y_next = polygon[(i + 1) % n]
        s += x_i * y_next - x_next * y_i
    return abs(s) / 2.0


# ══════════════════════════════════════════════════════════════════
#  ЗАДАНИЕ 2 — Лучевой тест (Ray Casting): точка в многоугольнике
# ══════════════════════════════════════════════════════════════════

def point_in_polygon(px: float, py: float, polygon: list[tuple]) -> bool:
    """
    Проверяет, находится ли точка (px, py) внутри многоугольника.

    Алгоритм Ray Casting:
    1. Из точки P бросаем горизонтальный луч вправо (→ +∞).
    2. Считаем, сколько рёбер многоугольника этот луч пересекает.
    3. Нечётное число пересечений → точка ВНУТРИ.

    Обработка вершин:
      Ребро A–B пересекает луч, только если:
        y_A <= py < y_B   или   y_B <= py < y_A
      (одна граница включена, другая нет — устраняет двойной счёт)

    Для каждого подходящего ребра находим x-координату пересечения
    луча с этим ребром и проверяем, что она > px (луч идёт вправо).

    Сложность: O(n) — один проход по всем рёбрам.
    """
    n = len(polygon)
    count = 0  # Счётчик пересечений

    for i in range(n):
        # Текущее ребро: A → B
        ax, ay = polygon[i]
        bx, by = polygon[(i + 1) % n]

        # Проверяем: py попадает между ay и by (одна граница включена)?
        if (ay <= py < by) or (by <= py < ay):
            # Вычисляем x-координату точки пересечения луча с ребром
            # Луч: y = py,  ребро: линейная интерполяция A→B
            # x_intersect = ax + (py - ay) / (by - ay) * (bx - ax)
            t = (py - ay) / (by - ay)
            x_intersect = ax + t * (bx - ax)

            # Пересечение считается, только если оно правее точки P
            if x_intersect > px:
                count += 1

    # Нечётное число пересечений → внутри
    return count % 2 == 1


