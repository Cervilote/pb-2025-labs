#  ЗАДАНИЕ 2 — Критический путь на DAG
# ══════════════════════════════════════════════════════════════════

# Граф проекта (DAG):
#   0→1 (3), 0→2 (2), 1→3 (4), 2→3 (5)
#   1→4 (6), 3→4 (2), 3→5 (3), 4→5 (1)

graph_project = {
    0: [(1, 3), (2, 2)],
    1: [(3, 4), (4, 6)],
    2: [(3, 5)],
    3: [(4, 2), (5, 3)],
    4: [(5, 1)],
    5: []
}


# --- 2.1  Топологическая сортировка (алгоритм Кана) ---------------

def topological_sort(graph: dict) -> list:
    """
    Линейно упорядочивает вершины DAG так, что для каждой дуги u→v
    вершина u стоит РАНЬШЕ v в результате.

    ─── Алгоритм Кана (на основе BFS) ───

    1. Для каждой вершины считаем in_degree — сколько дуг ВХОДИТ в неё.
       Вершины с in_degree = 0 не имеют зависимостей → можно начинать с них.

    2. Все вершины с in_degree = 0 добавляем в очередь.

    3. Пока очередь не пуста:
       a) Извлекаем вершину u → добавляем в результат
       b) Для каждого соседа v вершины u:
          - уменьшаем in_degree[v] на 1 (как бы «удаляем» дугу u→v)
          - если in_degree[v] стала 0 → добавляем v в очередь

    4. Если обработали все V вершин — порядок готов.
       Если нет — в графе есть цикл (это не DAG!).

    Сложность: O(V + E) — каждая вершина и дуга обрабатываются ровно 1 раз.
    """
    # Шаг 1: Вычисляем входящие степени
    in_degree = {v: 0 for v in graph}
    for u in graph:
        for v, _ in graph[u]:
            in_degree[v] += 1

    # Шаг 2: Собираем вершины с in_degree = 0
    queue = deque()
    for v in graph:
        if in_degree[v] == 0:
            queue.append(v)

    order = []  # Результат — топологический порядок

    # Шаг 3: BFS-подобный обход
    while queue:
        u = queue.popleft()
        order.append(u)

        for v, _ in graph[u]:
            in_degree[v] -= 1      # «удаляем» дугу u→v
            if in_degree[v] == 0:  # v больше ни от кого не зависит
                queue.append(v)

    # Шаг 4: Проверка на цикл
    if len(order) != len(graph):
        raise ValueError("Граф содержит цикл — невозможно выполнить топологическую сортировку!")

    return order


# --- 2.2  Критический путь (метод DP на DAG) ----------------------

def critical_path(graph: dict) -> tuple[int, list, list]:
    """
    Находит критический путь в DAG проекта.

    Возвращает:
      critical_time  — минимальное время завершения проекта
      critical_nodes — вершины, лежащие хотя бы на одном критическом пути
      path           — один конкретный критический путь (от истока до стока)

    ─── Как работает ───

    Шаг 1: Топологическая сортировка — определяем порядок обработки.

    Шаг 2: ПРЯМОЙ ПРОХОД (forward pass) — вычисляем earliest finish time:
       dist[v] = max(dist[u] + weight(u,v))  для всех дуг u→v
       Обрабатываем вершины в топологическом порядке, чтобы при
       обработке v все её предшественники u уже были вычислены.

    Шаг 3: Критическое время = dist[сток] (последняя вершина).

    Шаг 4: ОБРАТНЫЙ ПРОХОД (backward pass) — находим критические узлы:
       latest[v] — самый поздний допустимый срок начала обработки v
       latest[сток] = dist[сток]
       latest[u] = min(latest[v] - weight(u,v))  для всех дуг u→v
       Если latest[v] == dist[v], вершина v — критическая (запаса нет).

    Шаг 5: Восстановление одного критического пути.

    Сложность: O(V + E) — два прохода по всем вершинам и дугам.
    """
    # Шаг 1: Топологическая сортировка
    order = topological_sort(graph)

    # Шаг 2: Прямой проход — earliest finish times
    INF = float('-inf')
    dist = {v: INF for v in graph}
    pred = {v: None for v in graph}

    # Исток (первая вершина в топологическом порядке) — время 0
    source = order[0]
    dist[source] = 0

    for u in order:
        for v, w in graph[u]:
            # Расслабление «наоборот» — ищем МАКСИМУМ, а не минимум
            if dist[u] + w > dist[v]:
                dist[v] = dist[u] + w
                pred[v] = u

    # Шаг 3: Критическое время
    sink = order[-1]  # Последняя вершина = сток (финиш проекта)
    critical_time = dist[sink]

    # Шаг 4: Обратный проход — latest finish times
    latest = {v: float('inf') for v in graph}
    latest[sink] = dist[sink]

    # Идём в обратном топологическом порядке
    for u in reversed(order):
        for v, w in graph[u]:
            # latest[u] = min(latest[v] - w) по всем исходящим дугам
            if latest[v] - w < latest[u]:
                latest[u] = latest[v] - w

    # Критические узлы: те, у которых запас = 0 (latest == dist)
    critical_nodes = [v for v in order if dist[v] == latest[v] and dist[v] != INF]

    # Шаг 5: Восстановление одного критического пути
    path = restore_path(pred, source, sink)

    return critical_time, critical_nodes, path


