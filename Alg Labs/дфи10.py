# --- 1.2  Алгоритм Дейкстры --------------------------------------

def dijkstra(graph: dict, start: int) -> tuple[dict, dict]:
    """
    Находит кратчайшие расстояния от start до всех вершин
    во взвешенном ориентированном графе с неотрицательными весами.

    Возвращает:
      dist — {вершина: кратчайшее расстояние}
      pred — {вершина: предшественник на кратчайшем пути}

    ─── Как работает ───

    1. ИНИЦИАЛИЗАЦИЯ:
       - dist[start] = 0, все остальные = бесконечность (∞)
       - pred[v] = None для всех вершин
       - visited = пустое множество (раскрытые вершины)

    2. ГЛАВНЫЙ ЦИКЛ (повторяется V раз):
       a) Из всех НЕраскрытых вершин выбираем u с минимальным dist[u]
          (жадный выбор — берём самую «дешёвую» вершину)
       b) Отмечаем u как раскрытую (visited)
       c) РАССЛАБЛЕНИЕ (relaxation):
          Для каждого соседа v вершины u с весом дуги w:
            если dist[u] + w < dist[v]:
              обновляем dist[v] = dist[u] + w
              запоминаем pred[v] = u

    Почему это работает:
      Когда мы выбираем вершину u с минимальным dist[u] среди нераскрытых,
      мы уверены, что dist[u] — уже окончательный кратчайший путь.
      Ведь все неотрицательные веса гарантируют, что через другие
      нераскрытые вершины путь может быть только длиннее или равен.

    Реализация: поиск минимума перебором (без кучи).
    Сложность: O(V²) — на каждой из V итераций ищем min за O(V).
    """
    INF = float('inf')

    # Шаг 1: Инициализация
    dist = {v: INF for v in graph}   # Все расстояния = ∞
    pred = {v: None for v in graph}  # Предшественники не определены
    dist[start] = 0                  # До самого себя расстояние = 0
    visited = set()                  # Множество раскрытых вершин

    # Шаг 2: Главный цикл — повторяем V раз (по числу вершин)
    for _ in range(len(graph)):

        # 2a) Ищем нераскрытую вершину u с минимальным dist[u]
        #     Перебираем ВСЕ вершины — это O(V)
        u = None
        min_dist = INF
        for v in graph:
            if v not in visited and dist[v] < min_dist:
                min_dist = dist[v]
                u = v

        # Если не нашли — оставшиеся вершины недостижимы
        if u is None:
            break

        # 2b) Отмечаем u как раскрытую
        visited.add(u)

        # 2c) Расслабление (relaxation) — обходим соседей u
        for neighbor, weight in graph[u]:
            # Проверяем: может ли путь через u быть короче?
            new_dist = dist[u] + weight
            if new_dist < dist[neighbor]:
                dist[neighbor] = new_dist   # Нашли путь покороче!
                pred[neighbor] = u          # Запоминаем: пришли из u

    return dist, pred


# --- 1.3  Восстановление кратчайшего пути -------------------------

def restore_path(pred: dict, start: int, end: int) -> list | None:
    """
    Восстанавливает кратчайший путь по словарю предшественников.

    Идея: идём от end назад по цепочке pred[], пока не дойдём до start.
    Затем разворачиваем список.

    Пример:
      pred = {0: None, 2: 0, 1: 2, 3: 1, 4: 3}
      Путь 0 → 4:  4 ← 3 ← 1 ← 2 ← 0  →  разворот  →  [0, 2, 1, 3, 4]

    Сложность: O(V) — в худшем случае путь проходит через все вершины.
    """
    # Если end вообще недостижим (нет предшественника и это не start)
    if pred.get(end) is None and end != start:
        return None

    path = []
    current = end

    # Идём назад по предшественникам
    while current is not None:
        path.append(current)
        current = pred[current]

    # Проверяем, что дошли до start
    if path[-1] != start:
        return None

    # Разворачиваем: [4, 3, 1, 2, 0] → [0, 2, 1, 3, 4]
    path.reverse()
    return path


